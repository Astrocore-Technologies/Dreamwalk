export const dictionaries: Record<Locale, Record<string, string>> = {
  ru: Object.fromEntries(Object.entries(messages).map(([key, value]) => [key, value.ru])),
  en: Object.fromEntries(Object.entries(messages).map(([key, value]) => [key, value.en])),
  uk: Object.fromEntries(Object.entries(messages).map(([key, value]) => [key, value.uk])),
};
export type TranslationParams = Record<string, string | number>;
/** Trim only for lookup: JSX may include whitespace around an otherwise identical key. */
export function translate(locale: Locale, key: string, params: TranslationParams = {}): string {
  const normalized = key.trim();
  const value = dictionaries[locale][key] ?? dictionaries[locale][normalized];
  if (value === undefined) {
    if (process.env.NODE_ENV !== 'production')
      console.warn(`[i18n] Missing ${locale} key: ${normalized}`);
    return { ru: '[Перевод отсутствует]', en: '[Translation missing]', uk: '[Переклад відсутній]' }[
      locale
    ];
  }
  const leading = key.slice(0, key.length - key.trimStart().length);
  const trailing = key.slice(key.trimEnd().length);
  const text = value.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, name: string) =>
    String(params[name] ?? placeholder),
  );
  return key === normalized ? text : leading + text + trailing;
}
export function formatDate(
  locale: Locale,
  value: string | Date,
  options: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short', year: 'numeric' },
): string {
  const date = typeof value === 'string' ? new Date(value) : value;
  return Number.isNaN(date.getTime())
    ? '—'
    : new Intl.DateTimeFormat(intlLocales[locale], options).format(date);
}
export function formatNumber(
  locale: Locale,
  value: number,
  options?: Intl.NumberFormatOptions,
): string {
  return new Intl.NumberFormat(intlLocales[locale], options).format(value);
}
export function plural(
  locale: Locale,
  count: number,
  forms: { one: string; few?: string; many?: string; other: string },
): string {
  const category = new Intl.PluralRules(intlLocales[locale]).select(count);
  return (forms[category as keyof typeof forms] ?? forms.other).replace(
    '{count}',
    formatNumber(locale, count),
  );
}
/** A full localized count, e.g. “1 adventure”, “2 пригоди”, “5 приключений”. */
export function formatCount(
  locale: Locale,
  count: number,
  noun: 'adventure' | 'player' = 'adventure',
): string {
  const forms = {
    adventure: {
      en: { one: '{count} adventure', other: '{count} adventures' },
      uk: {
        one: '{count} пригода',
        few: '{count} пригоди',
        many: '{count} пригод',
        other: '{count} пригоди',
      },
      ru: {
        one: '{count} приключение',
        few: '{count} приключения',
        many: '{count} приключений',
        other: '{count} приключения',
      },
    },
    player: {
      en: { one: '{count} player', other: '{count} players' },
      uk: {
        one: '{count} гравець',
        few: '{count} гравці',
        many: '{count} гравців',
        other: '{count} гравця',
      },
      ru: {
        one: '{count} игрок',
        few: '{count} игрока',
        many: '{count} игроков',
        other: '{count} игрока',
      },
    },
  };
  return plural(locale, count, forms[noun][locale]);
}
